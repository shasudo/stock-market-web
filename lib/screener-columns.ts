/**
 * Removes unrecognized picker IDs from a value received over the network.
 * The browser uses the same list, but this keeps the server-side resolver from
 * accepting arbitrary group or item names.
 */
export function normalizeAddColumnSelection(
  value: unknown,
): AddColumnSelection {
  if (!isRecord(value)) return emptyAddColumnSelection;

  const requestedTimeframes = Array.isArray(value.timeframes)
    ? value.timeframes.filter(
        (item): item is string => typeof item === "string",
      )
    : [];
  const knownTimeframes = new Set<string>(
    ADD_TIMEFRAMES.map((item) => item.id),
  );
  const timeframes = unique(
    requestedTimeframes.filter((item) => knownTimeframes.has(item)),
  );

  const requestedGroups = isRecord(value.groups) ? value.groups : {};
  const groups: Record<string, string[]> = {};
  for (const group of ADD_COLUMN_GROUPS) {
    const requested = requestedGroups[group.id];
    if (!Array.isArray(requested)) continue;
    const knownItems = new Set(group.items.map((item) => item.id));
    const items = unique(
      requested.filter(
        (item): item is string =>
          typeof item === "string" && knownItems.has(item),
      ),
    );
    if (items.length > 0) groups[group.id] = items;
  }

  return { timeframes, groups };
}

/**
 * Produces the canonical column identifiers shared by the picker, table, CSV
 * export and server-side value resolver. Keeping this mapping in one place
 * prevents a selected option from rendering under a different key than the
 * one used to retrieve its value.
 */
export function buildAddedColumnDefinitions(
  selection: AddColumnSelection,
): AddedColumnDefinition[] {
  if (selection.timeframes.length === 0) return [];

  const selectedItems = ADD_COLUMN_GROUPS.flatMap((group) =>
    (selection.groups[group.id] || [])
      .map((itemId) => group.items.find((item) => item.id === itemId))
      .filter((item): item is { id: string; label: string } => Boolean(item))
      .map((item) => ({ group, item })),
  );

  return ADD_TIMEFRAMES.filter((timeframe) =>
    selection.timeframes.includes(timeframe.id),
  ).flatMap((timeframe): AddedColumnDefinition[] => {
    if (selectedItems.length === 0) {
      return [
        {
          id: `${timeframe.id}:change`,
          timeframeId: timeframe.id,
          timeframeLabel: timeframe.label,
          label: timeframe.changeLabel,
          groupId: null,
          groupLabel: "Timeframe",
          itemId: null,
          kind: "change",
        },
      ];
    }
    return selectedItems.map(({ group, item }) => ({
      id: `${timeframe.id}:${group.id}:${item.id}`,
      timeframeId: timeframe.id,
      timeframeLabel: timeframe.label,
      label: item.label,
      groupId: group.id,
      groupLabel: group.label,
      itemId: item.id,
      kind: "option",
    }));
  });
}

export function selectionItemLabels(
  selection: AddColumnSelection,
  groups: AddColumnGroupOption[] = ADD_COLUMN_GROUPS,
): string[] {
  const labels: string[] = [];
  for (const group of groups) {
    for (const itemId of selection.groups[group.id] ?? []) {
      const item = group.items.find((i) => i.id === itemId);
      if (item) labels.push(item.label);
    }
  }
  return labels;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function unique(values: readonly string[]): string[] {
  return [...new Set(values)];
}
