function flatten(): MonthlyReturnArchive {
  const result: Record<string, number> = {};
  for (const [year, months] of Object.entries(ROWS)) {
    months.forEach((value, monthIndex) => {
      if (value === null) return;
      result[`${year}-${String(monthIndex + 1).padStart(2, "0")}`] = value;
    });
  }
  return result;
}

